#!/usr/bin/env python3
"""Fetch a pinned upstream and apply the locked Mod patch in a new external workspace."""
import argparse
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import struct
import subprocess
import sys
import tarfile
import tempfile
from urllib.parse import urlsplit
import zlib

KIT = Path(__file__).resolve().parents[1]
NOTICE_FILES = (
    'LICENSE', 'LICENSE_SCOPE.md', '使用协议.md',
    'docs/third-party-notices.md', 'docs/gpl-components.md',
    'docs/gpl-components.json', 'docs/generated-data-provenance.md',
    'docs/release-governance.md', 'docs/historical-release-review.md',
    'docs/split-releases.md', 'docs/upstream-merge-policy.md',
    'docs/source-update-2026-10-30.md',
    'docs/stable-acceptance-2026-10-30.md', 'docs/stable-acceptance-2026-10-30.json',
    'licenses/README.md', 'licenses/MacNativeGames-LICENSE',
    'licenses/GPL-2.0-only.txt', 'licenses/Lotuskit-LICENSE',
    'licenses/Marc-Robledo-equipment-MIT.txt',
    'licenses/DataPack-paiyge-MIT.txt',
)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def safe_name(name):
    p = PurePosixPath(name)
    if not name or p.is_absolute() or '..' in p.parts or '.git' in p.parts or '\\' in name or str(p) != name:
        raise ValueError('Unsafe manifest path')
    return name


def load_lock():
    lock = json.loads((KIT / 'upstream.lock.json').read_text())
    if lock.get('schemaVersion') != 1:
        raise ValueError('Unsupported upstream lock format')
    up = lock['upstream']
    u = urlsplit(up['url'])
    if u.scheme != 'https' or u.hostname != 'github.com' or u.username or u.password or u.query or u.fragment:
        raise ValueError('Upstream must be a credential-free GitHub HTTPS URL')
    if not re.fullmatch('[0-9a-f]{40}', up['commit']):
        raise ValueError('An exact upstream commit is required')
    names = []
    for row in lock['files']:
        names.append(safe_name(row['path']))
        if 'baseCommit' in row and not re.fullmatch('[0-9a-f]{40}', row['baseCommit']):
            raise ValueError('Invalid per-file compatibility commit')
        if not re.fullmatch('[0-9a-f]{64}', row['sha256']):
            raise ValueError('Invalid target digest')
        if row['baseSha256'] is not None and not re.fullmatch('[0-9a-f]{64}', row['baseSha256']):
            raise ValueError('Invalid base digest')
    if len(set(names)) != len(names):
        raise ValueError('Duplicate source path')
    for patch in lock['patches']:
        path = KIT / safe_name(patch['path'])
        if path.is_symlink() or sha(path) != patch['sha256']:
            raise ValueError('Patch digest mismatch; no network or source change performed')
        if b'GIT binary patch' in path.read_bytes():
            raise ValueError('Binary patch payloads are not allowed')
    return lock


def git(repository, *args, capture=False):
    return subprocess.run(['git', '-c', 'core.hooksPath=/dev/null', '-C', str(repository), *args],
                          check=True, stdout=subprocess.PIPE if capture else None).stdout


def png(width, height, rgb):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)
    pixels = (b'\0' + bytes(rgb) * width) * height
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(pixels)) + chunk(b'IEND', b''))


def loading_assets(source, supplied=None):
    target = source / 'games/totk/assets/branding/loading'
    target.mkdir(parents=True)
    names = ('background.png', 'logo.svg', 'footer.png')
    if supplied is not None:
        supplied = supplied.expanduser().resolve()
        for name in names:
            path = supplied / name
            if path.is_symlink() or not path.is_file() or not path.stat().st_size:
                raise ValueError('External loading assets must contain three regular nonempty files')
            shutil.copy2(path, target / name)
        origin = 'User-supplied external assets; authorization must be checked by the user'
    else:
        (target / 'background.png').write_bytes(png(1920, 1080, (15, 23, 27)))
        (target / 'footer.png').write_bytes(png(1920, 149, (21, 35, 39)))
        (target / 'logo.svg').write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 720 140">'
            '<text x="0" y="80" fill="#dbe9de" font-family="sans-serif" font-size="48">Native Adventure Kit</text></svg>\n')
        origin = 'Neutral placeholders generated by prepare_native.py; no original game/Figma artwork'
    (target / 'source.json').write_text(json.dumps({'origin': origin}, indent=2) + '\n')
    return {p.relative_to(source).as_posix(): sha(p) for p in target.iterdir()}


def verify_sources(source, lock, assets):
    expected = {row['path']: row['sha256'] for row in lock['files']}
    expected.update(assets)
    actual = set()
    if (source / '.git').is_symlink():
        raise ValueError('Source Git metadata must not be a symlink')
    for path in source.rglob('*'):
        if '.git' in path.relative_to(source).parts:
            continue
        if path.is_symlink():
            raise ValueError('Symlinks are not allowed in the assembled source')
        if path.is_file():
            relative = path.relative_to(source)
            # Host tests may create interpreter caches next to known Python sources.
            # Verify source bytes, not disposable bytecode; unknown cache names still fail.
            if relative.parent.name == '__pycache__' and relative.suffix == '.pyc':
                original = relative.parent.parent / (relative.name.split('.')[0] + '.py')
                if original.as_posix() in expected:
                    continue
            name = relative.as_posix()
            actual.add(name)
            if name not in expected or sha(path) != expected[name]:
                raise ValueError('Source changed or unexpected file found: ' + name)
    if actual != set(expected):
        raise ValueError('Assembled source is missing locked files')
    for row in lock['files']:
        if bool((source / row['path']).stat().st_mode & 0o111) != row['executable']:
            raise ValueError('Executable mode mismatch: ' + row['path'])


def verify(work, lock):
    info = json.loads((work / '.nak-workspace.json').read_text())
    if info['upstreamCommit'] != lock['upstream']['commit'] or info['lockSha256'] != sha(KIT / 'upstream.lock.json'):
        raise ValueError('Workspace was created from a different lock')
    verify_sources(work / 'MacNativeGames', lock, info['assetHashes'])
    print('Verified locked source files and loading assets; no game was built or started.')


def prepare(work, lock, cache=None, supplied_assets=None):
    if work.exists() or work.is_symlink():
        raise ValueError('Workspace already exists; use --verify or choose a new path. Nothing was overwritten.')
    if work == KIT or KIT in work.parents:
        raise ValueError('Workspace must be outside this kit repository')
    work.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.nak-prepare-', dir=work.parent) as temporary:
        temporary = Path(temporary)
        upstream = cache.expanduser().resolve() if cache else temporary / 'upstream'
        if not cache:
            upstream.mkdir()
            git(upstream, 'init', '-q')
            for source_commit in sorted({lock['upstream']['commit']} | {r['baseCommit'] for r in lock['files'] if 'baseCommit' in r}):
                git(upstream, 'fetch', '--depth=1', lock['upstream']['url'], source_commit)
        # --upstream-cache is strictly read-only: no fetch, checkout, clean or reset.
        commit = git(upstream, 'rev-parse', lock['upstream']['commit'] + '^{commit}', capture=True).decode().strip()
        if commit != lock['upstream']['commit']:
            raise ValueError('Cached commit does not match lock')
        stage = temporary / 'workspace'
        source = stage / 'MacNativeGames'
        source.mkdir(parents=True)
        paths = [row['path'] for row in lock['files'] if row['baseSha256'] is not None]
        archive = git(upstream, 'archive', '--format=tar', commit, '--', *paths, capture=True)
        found = set()
        with tarfile.open(fileobj=io.BytesIO(archive)) as bundle:
            for member in bundle:
                if member.isdir():
                    continue
                name = safe_name(member.name)
                if not member.isfile() or name not in paths:
                    raise ValueError('Unexpected upstream archive entry')
                path = source / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(bundle.extractfile(member).read())
                path.chmod(0o755 if member.mode & 0o111 else 0o644)
                found.add(name)
        if found != set(paths):
            raise ValueError('Pinned upstream is missing expected paths')
        for row in lock['files']:
            if row.get('baseCommit') and row['baseSha256'] is not None:
                # Explicitly pinned compatibility inputs, verified like the primary tree.
                data = git(upstream, 'show', row['baseCommit'] + ':' + safe_name(row['path']), capture=True)
                (source / row['path']).write_bytes(data)
            if row['baseSha256'] is not None and sha(source / row['path']) != row['baseSha256']:
                raise ValueError('Upstream file digest mismatch: ' + row['path'])
        git(source, 'init', '-q')
        for patch in lock['patches']:
            path = KIT / patch['path']
            git(source, 'apply', '--check', '--whitespace=nowarn', str(path))
            git(source, 'apply', '--whitespace=nowarn', str(path))
        for row in lock['files']:
            if 'transform' not in row:
                continue
            if row['path'] != 'games/totk/assets/shader_list.tsv' or row['transform'] != 'canonical-shader-list-v1':
                raise ValueError('Unknown compatibility transform')
            script = source / 'games/totk/scripts/shader_list.py'
            expected_script = next(r['sha256'] for r in lock['files'] if r['path'] == 'games/totk/scripts/shader_list.py')
            if sha(script) != expected_script:
                raise ValueError('Unverified shader normalization script')
            canonical = stage / 'canonical.tsv'
            subprocess.run([sys.executable, '-B', str(script), 'merge', str(canonical), str(source / row['path'])], check=True)
            canonical.replace(source / row['path'])
        # Keep fresh local Git metadata for the upstream repository-policy checker;
        # no original local history, refs or credentials are copied.
        assets = loading_assets(source, supplied_assets)
        verify_sources(source, lock, assets)
        git(source, 'add', '-f', '.')
        for name in NOTICE_FILES:
            destination = stage / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(KIT / name, destination)
        (stage / '.nak-workspace.json').write_text(json.dumps({
            'upstreamCommit': commit, 'lockSha256': sha(KIT / 'upstream.lock.json'),
            'assetHashes': assets, 'gameBuilt': False}, indent=2) + '\n')
        # Recheck immediately before rename; never merge into an existing workspace.
        if work.exists() or work.is_symlink():
            raise ValueError('Workspace appeared during preparation; refusing to overwrite it')
        stage.rename(work)
    print('Prepared: ' + str(work / 'MacNativeGames'))
    print('Only pinned sources were assembled. Supply your own game/update/keys for a separate build.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--work', required=True, type=Path, help='New workspace outside this repository')
    parser.add_argument('--upstream-cache', type=Path, help='Read-only local Git cache containing the exact pinned commit')
    parser.add_argument('--loading-assets', type=Path, help='Optional user-authorized background.png, logo.svg and footer.png')
    parser.add_argument('--verify', action='store_true', help='Verify existing assembled files; never download or modify them')
    args = parser.parse_args()
    lock = load_lock()
    # Do not resolve the final component: an existing dangling symlink is also rejected.
    work = args.work.expanduser().absolute()
    work = work.parent.resolve() / work.name
    if args.verify:
        verify(work, lock)
    else:
        prepare(work, lock, args.upstream_cache, args.loading_assets)


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as exc:
        print('Preparation stopped: ' + str(exc), file=sys.stderr)
        sys.exit(1)
